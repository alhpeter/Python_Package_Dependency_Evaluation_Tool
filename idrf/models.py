"""
IDRF Core Data Models
---------------------

WHY THIS FILE EXISTS
--------------------
This module defines the two primary structured objects used throughout IDRF:

1. PackageNode
   = internal representation of one dependency package and its public metadata.

2. InsightCard
   = analyst-facing reasoning artifact generated by the investigative engine.

GROUNDING TO PROJECT
--------------------
This file operationalizes:

- Proposal Section 5.2 (Dependency Modeling and Structural Analysis)
- Proposal Section 5.3 (Investigative Reasoning and Insight Generation)
- GitHub Issues #2, #14, #16, #18, #21

The data classes are intentionally minimal and transparent so that:

- every field has methodological justification,
- every output is explainable during conference defense,
- no hidden black-box state exists.
"""

from dataclasses import dataclass, field
from typing import Any, Dict, List


@dataclass
class PackageNode:
    """
    Structured representation of one software dependency node.

    PARAMETERS
    ----------
    name : str
        Canonical package name.

    direct_dependencies : List[str]
        Immediate bounded child dependencies retained from PyPI metadata.

        WHY THIS FIELD EXISTS:
        ----------------------
        This is required to construct the dependency graph edges.
        GitHub Issues #14 and #16 explicitly require direct dependency ETL
        and graph construction.

        V4 prototype intentionally stores only bounded immediate children
        to preserve conference-time interpretability.

    maintainer_count : int
        Conservative maintainer concentration proxy.

        WHY:
        PyPI does not always expose reliable maintainer team cardinality.
        Therefore IDRF uses a bounded proxy variable rather than pretending
        to know exact organizational staffing.

    stars : int
        GitHub star count used as weak ecosystem visibility signal.

    last_update_days : int
        Days since last GitHub push used as maintenance staleness signal.
    """

    name: str
    direct_dependencies: List[str] = field(default_factory=list)
    maintainer_count: int = 1
    stars: int = 0
    last_update_days: int = 365


@dataclass
class InsightCard:
    """
    Human-facing structured reasoning output.

    WHY THIS OBJECT EXISTS
    ----------------------
    Raw metric tables are not the end goal of IDRF.

    The proposal's novelty is the transformation of graph observations into
    analyst-readable investigative prompts.

    Hence each surfaced concern is encapsulated as an InsightCard.

    PARAMETERS
    ----------
    package : str
        Dependency package being flagged.

    investigative_priority_score : float
        Weighted transparent priority ranking.

    finding : str
        Human-readable summary of why package was surfaced.

    rationale : str
        Reasoning explanation linking metrics + metadata.

    recommended_question : str
        Follow-up investigative prompt for analyst decision-making.
    """

    package: str
    investigative_priority_score: float
    finding: str
    rationale: str
    recommended_question: str
    evidence: Dict[str, Any] = field(default_factory=dict)
    triggered_rules: List[str] = field(default_factory=list)
    investigation_profile: List[str] = field(default_factory=list)
    confidence: str = "moderate"

    def __str__(self):
        return (
            f"[{self.package}] Priority={self.investigative_priority_score}\n"
            f"Finding: {self.finding}\n"
            f"Rationale: {self.rationale}\n"
            f"Investigative Prompt: {self.recommended_question}"
        )